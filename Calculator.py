Num1=int(input('Enter a number'))
Num2=int(input('Enter a 2nd Number'))
Enter=input('Enter a symbol +,-,*,/:')
if(Enter=='+'):
    print('Num1+Num2=',Num1+Num2)
elif(Enter=='-'):
     print('Num1-Num2=',Num1-Num2)
elif(Enter=='*'):
      print('Num1×Num2=',Num1*Num2)
elif(Enter=='/'):
    print('Num1/Num2=',Num1/Num2)
